/**
 * Export report as PDF (using browser print)
 */
export function exportAsPDF(report: ScanReport): void {
  // Generate HTML content
  exportAsHTML(report, 'temp-report.html');
  
  // Note: For true PDF generation, consider using a library like jsPDF or pdfmake
  // For now, we'll use the browser's print dialog
  setTimeout(() => {
    window.print();
  }, 500);
}

/**
 * Helper: Download blob as file
 */
function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Get export format options
 */
export const exportFormats = [
  { value: 'json', label: 'JSON', icon: '📄', description: 'Machine-readable format' },
  { value: 'csv', label: 'CSV', icon: '📊', description: 'Spreadsheet format' },
  { value: 'html', label: 'HTML', icon: '🌐', description: 'Web page format' },
  { value: 'md', label: 'Markdown', icon: '📝', description: 'Documentation format' },
] as const;

export type ExportFormat = typeof exportFormats[number]['value'];

/**
 * Export report in specified format
 */
export function exportReport(report: ScanReport, format: ExportFormat): void {
  switch (format) {
    case 'json':
      exportAsJSON(report);
      break;
    case 'csv':
      exportAsCSV(report);
      break;
    case 'html':
      exportAsHTML(report);
      break;
    case 'md':
      exportAsMarkdown(report);
      break;
    default:
      console.error('Unknown export format:', format);
  }
}
