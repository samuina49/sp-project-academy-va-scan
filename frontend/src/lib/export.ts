/**
 * Export Utility Functions
 * Handles exporting scan reports in various formats
 */

interface VulnerabilityFinding {
  line: number;
  type: string;
  severity: 'critical' | 'high' | 'medium' | 'low';
  message: string;
  cwe?: string;
  owasp?: string;
  confidence?: number;
  code_snippet?: string;
}

interface ScanReport {
  scan_id: string;
  filename: string;
  language: string;
  timestamp: string;
  scan_time_ms: number;
  findings: VulnerabilityFinding[];
  summary: {
    total: number;
    critical: number;
    high: number;
    medium: number;
    low: number;
  };
}

/**
 * Export report as JSON
 */
export function exportAsJSON(report: ScanReport, filename?: string): void {
  const json = JSON.stringify(report, null, 2);
  const blob = new Blob([json], { type: 'application/json' });
  downloadBlob(blob, filename || `scan-report-${report.scan_id}.json`);
}

/**
 * Export report as CSV
 */
export function exportAsCSV(report: ScanReport, filename?: string): void {
  const headers = ['Line', 'Type', 'Severity', 'Message', 'CWE', 'OWASP', 'Confidence'];
  const rows = report.findings.map((f) => [
    f.line,
    f.type,
    f.severity,
    `"${f.message.replace(/"/g, '""')}"`, // Escape quotes
    f.cwe || '',
    f.owasp || '',
    f.confidence || '',
  ]);

  const csv = [
    headers.join(','),
    ...rows.map((row) => row.join(',')),
  ].join('\n');

  const blob = new Blob([csv], { type: 'text/csv' });
  downloadBlob(blob, filename || `scan-report-${report.scan_id}.csv`);
}

/**
 * Export report as Markdown
 */
export function exportAsMarkdown(report: ScanReport, filename?: string): void {
  const md = `# Vulnerability Scan Report

**Scan ID:** ${report.scan_id}  
**File:** ${report.filename}  
**Language:** ${report.language}  
**Date:** ${new Date(report.timestamp).toLocaleString()}  
**Scan Time:** ${report.scan_time_ms}ms

## Summary

- **Total Findings:** ${report.summary.total}
- 🔴 **Critical:** ${report.summary.critical}
- 🟠 **High:** ${report.summary.high}
- 🟡 **Medium:** ${report.summary.medium}
- 🟢 **Low:** ${report.summary.low}

## Vulnerabilities

${report.findings
  .map(
    (f, i) => `### ${i + 1}. ${f.type} (${f.severity.toUpperCase()})

**Line:** ${f.line}  
**Message:** ${f.message}  
${f.cwe ? `**CWE:** ${f.cwe}  ` : ''}${f.owasp ? `**OWASP:** ${f.owasp}  ` : ''}${f.confidence ? `**Confidence:** ${(f.confidence * 100).toFixed(1)}%  ` : ''}

${f.code_snippet ? '```\n' + f.code_snippet + '\n```\n' : ''}`
  )
  .join('\n\n')}

---
*Generated by VulnScanner - AI-based Vulnerability Detection*
`;

  const blob = new Blob([md], { type: 'text/markdown' });
  downloadBlob(blob, filename || `scan-report-${report.scan_id}.md`);
}

